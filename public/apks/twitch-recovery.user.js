(function () {
  'use strict';

/* Storage adapter for the Tampermonkey userscript.
 * Uses the legacy synchronous GM_* API when granted (broadest compatibility, works in
 * Violentmonkey / Greasemonkey / Tampermonkey alike), and falls back to localStorage when the
 * script is installed with @grant none. */

function createStorageAdapter() {
  const hasLegacyGm =
    typeof GM_getValue === 'function' &&
    typeof GM_setValue === 'function' &&
    typeof GM_deleteValue === 'function';

  if (hasLegacyGm) {
    return {
      get(key) {
        return Promise.resolve(GM_getValue(key, undefined));
      },
      set(key, value) {
        return Promise.resolve(GM_setValue(key, value));
      },
      remove(key) {
        return Promise.resolve(GM_deleteValue(key));
      },
    };
  }

  console.warn('[Twitch Recovery] GM_* storage unavailable, falling back to localStorage');
  return createLocalStorageAdapter();
}

function createLocalStorageAdapter() {
  return {
    get(key) {
      return Promise.resolve(localStorage.getItem(key));
    },
    set(key, value) {
      return Promise.resolve(localStorage.setItem(key, JSON.stringify(value)));
    },
    remove(key) {
      return Promise.resolve(localStorage.removeItem(key));
    },
  };
}

/* =============================================================================
 * Twitch Error 3000 Auto-Recovery — 共用核心 (Shared Core)
 * -----------------------------------------------------------------------------
 * 這是唯一的邏輯來源。chrome 擴充套件與 Tampermonkey 腳本都由 build.js 內嵌
 * 同一份本檔案，僅外層的 storage adapter 不同，確保兩種載體行為完全一致。
 *
 * 本檔案「不得」直接引用 chrome.* 或 GM_*，一律透過注入的 storage adapter：
 *     adapter.get(key)         -> Promise<value | undefined>
 *     adapter.set(key, value)  -> Promise<void>
 *     adapter.remove(key)      -> Promise<void>
 * ========================================================================== */

const STORAGE_KEY = 'twitch_recovery';
const COOLDOWN_MS = 15000; // 恢復後 15 秒內不再觸發
const MAX_RECOVERIES = 5; // 每 5 分鐘最多恢復 5 次，防止死循環
const DEBOUNCE_MS = 800; // DOM 變化後 800ms 內合併檢查
const HEARTBEAT_MS = 3000; // 每 3 秒儲存一次播放位置
const RELOAD_DELAY_MS = 300; // storage 寫入完成後再延遲 reload，確保落盤
const RESTORE_TTL_MS = 30000; // 還原資料有效期
const RESET_INTERVAL_MS = 5 * 60 * 1000; // 恢復次數重置週期
const OBSERVER_DELAY_MS = 4000; // 等頁面渲染穩定後才啟動 DOM 觀察
const FALLBACK_POLL_MS = 30000; // 兜底全量掃描間隔
const FS_SUPPRESS_MS = 3000; // 進入全螢幕後抑制檢測
const FS_RESTORE_DELAY_MS = 5000; // reload 後等待播放器渲染再請求全螢幕
const FS_RESTORE_MAX_TRIES = 5;
const FS_RESTORE_INTERVAL_MS = 3000;

const TAG = '[Twitch Recovery]';

/**
 * Twitch 是 SPA，切換頻道不會 reload。location.href 帶大量埋點 query，
 * 只保留決定「是哪部影片」的參數，其餘雜訊全部剔除後才拿來比對。
 */
function normalizeUrl(href) {
  try {
    const u = new URL(href);
    u.hash = '';
    const kept = new URLSearchParams();
    const videos = u.searchParams.get('videos');
    const video = u.searchParams.get('video');
    if (videos) kept.append('videos', videos);
    if (video) kept.append('video', video);
    u.search = kept.toString();
    return u.toString();
  } catch (e) {
    return href;
  }
}

/** 跨瀏覽器的可見性判定（避免 hidden / display:none 的假陽性） */
function isVisible(el) {
  if (!el) return false;
  if (typeof el.checkVisibility === 'function') {
    try {
      return el.checkVisibility();
    } catch (e) {
      /* fallthrough */
    }
  }
  return el.offsetParent !== null;
}

function isError3000Visible() {
  // 優先：檢查 Twitch 特定的 error overlay 元素（最準確）
  const selectors = [
    '[data-test-selector="content-overlay-gate"]',
    '.content-overlay-gate',
    '.player-overlay-background',
    '[data-a-target="player-overlay-gate"]',
    '.video-player__overlay',
  ];

  for (const sel of selectors) {
    const el = document.querySelector(sel);
    // 只用 innerText（排除 display:none/hidden 的子元素）
    if (el && /3000|decoding|解碼|デコード|decod/i.test(el.innerText || '')) {
      return true;
    }
  }

  // 備用（收窄範圍）：檢查錯誤相關 class 的元素
  // 要求 "3000" + error 關鍵字同時出現在同一個元素文字中（跨子元素合併）
  // 使用 innerText 而非 textContent，避免 hidden/script 內容干擾
  const fallbackElements = document.querySelectorAll("div[class*='overlay'], div[class*='error']");
  for (const el of fallbackElements) {
    const text = (el.innerText || '').trim();
    if (!text || text.length > 300) continue;
    if (!isVisible(el)) continue;
    if (/\b3000\b/.test(text) && /(?:error|錯誤|エラ|decod|解碼|デコード)/i.test(text)) {
      return true;
    }
  }
  return false;
}

function getVodTime() {
  const video = document.querySelector('video');
  if (!video || video.duration === Infinity || isNaN(video.duration)) {
    return null;
  }
  return Math.floor(video.currentTime);
}

/**
 * 建立恢復器。
 * @param {object} storage storage adapter（見檔頭契約）
 * @param {object} [options]
 * @param {boolean} [options.autoReload=true] false 時偵測到錯誤只記錄不 reload（除錯用）
 */
function createTwitchRecovery(storage, options) {
  const opts = Object.assign({ autoReload: true }, options || {});

  let lastSavedTime = null;
  let lastFullscreenState = false;
  let lastSavedUrl = normalizeUrl(location.href);
  let lastRecoveryTime = 0;
  let recoveryCount = 0;
  let debounceTimer = null;
  let fullscreenSuppressUntil = 0;

  function log(...args) {
    console.log(TAG, ...args);
  }
  function warn(...args) {
    console.warn(TAG, ...args);
  }

  // ---- 播放位置心跳 ----

  async function saveHeartbeat() {
    const vodTime = getVodTime();
    const isFS = document.fullscreenElement !== null;
    const changed = (vodTime != null && vodTime !== lastSavedTime) || isFS !== lastFullscreenState;

    if (!changed) return;

    if (vodTime != null) lastSavedTime = vodTime;
    lastFullscreenState = isFS;

    await storage.set(STORAGE_KEY, {
      url: location.href,
      normalizedUrl: lastSavedUrl,
      vodTime: vodTime != null ? vodTime : lastSavedTime,
      timestamp: Date.now(),
      wasFullscreen: isFS,
    });
  }

  // ---- 重新載入 ----

  async function saveAndReload() {
    // 最後一次心跳，確保取得最新位置。
    // 若 getVodTime() 失敗（error 3000 時 video 可能已損毀），fallback 到上次心跳值
    const vodTime = getVodTime();
    const wasFullscreen = document.fullscreenElement !== null;

    await storage.set(STORAGE_KEY, {
      url: location.href,
      normalizedUrl: lastSavedUrl,
      vodTime: vodTime != null ? vodTime : lastSavedTime,
      timestamp: Date.now(),
      wasFullscreen: wasFullscreen,
    });

    // 延遲 reload 確保 storage 寫入已落盤
    setTimeout(() => location.reload(), RELOAD_DELAY_MS);
  }

  // ---- 還原 ----

  async function tryRestore() {
    const data = await storage.get(STORAGE_KEY);
    if (!data) return;

    await storage.remove(STORAGE_KEY);

    if (Date.now() - (data.timestamp || 0) > RESTORE_TTL_MS) return;

    // SPA 切換過頻道就別套用舊進度，否則會跳到不相干的時間點
    const savedUrl = data.normalizedUrl || normalizeUrl(data.url || '');
    if (savedUrl && savedUrl !== normalizeUrl(location.href)) return;

    if (data.vodTime != null && data.vodTime > 0) {
      restoreVodTime(data.vodTime);
    }
    if (data.wasFullscreen) {
      restoreFullscreen();
    }
  }

  function restoreFullscreen() {
    // 等播放器渲染完成後再請求全螢幕，多次嘗試
    const attempt = (delay, maxTries, currentTry) => {
      if (currentTry >= maxTries) return;
      setTimeout(() => {
        // 優先嘗試 player container，fallback 到 video / document
        const el =
          document.querySelector('.video-player__container') ||
          document.querySelector('[data-a-target="player-container"]') ||
          document.querySelector('video') ||
          document.documentElement;
        if (el && el.requestFullscreen) {
          el.requestFullscreen()
            .then(() => log('Fullscreen restored'))
            .catch(() => attempt(FS_RESTORE_INTERVAL_MS, maxTries, currentTry + 1));
        } else {
          attempt(FS_RESTORE_INTERVAL_MS, maxTries, currentTry + 1);
        }
      }, delay);
    };
    attempt(FS_RESTORE_DELAY_MS, FS_RESTORE_MAX_TRIES, 0);
  }

  function restoreVodTime(targetTime) {
    const trySeek = (video, attempts) => {
      if (attempts <= 0) return;
      if (video.readyState >= 2 && !isNaN(video.duration)) {
        log(`Seeking to ${targetTime}s`);
        video.currentTime = targetTime;
        const played = video.play();
        // 自動播放被瀏覽器政策擋下是常況，不應讓未捕捉的 Promise 打斷恢復流程
        if (played && typeof played.catch === 'function') {
          played.catch(() => log('Autoplay blocked by browser policy, position still restored'));
        }
        return;
      }
      setTimeout(() => {
        const v = document.querySelector('video');
        if (v) trySeek(v, attempts - 1);
      }, 1500);
    };

    const interval = setInterval(() => {
      const video = document.querySelector('video');
      if (video && video.duration > 0 && !isNaN(video.duration)) {
        clearInterval(interval);
        trySeek(video, 10);
      }
    }, 800);

    setTimeout(() => clearInterval(interval), 20000);
  }

  // ---- 全螢幕抑制（避免按 F 進入全螢幕時被誤判） ----

  function onFullscreenChange() {
    if (document.fullscreenElement) {
      // 進入全螢幕時 Twitch 重構 DOM，短期內抑制檢測避免誤觸
      fullscreenSuppressUntil = Date.now() + FS_SUPPRESS_MS;
      log('Fullscreen on, detection suppressed 3s');
    }
  }

  // ---- 錯誤檢測（事件驅動，零輪詢開銷） ----

  function triggerCheck() {
    if (Date.now() < fullscreenSuppressUntil) return;
    if (!isError3000Visible()) return;

    const now = Date.now();
    if (now - lastRecoveryTime < COOLDOWN_MS) return;
    if (recoveryCount >= MAX_RECOVERIES) {
      warn('Too many recoveries, reload loop prevented.');
      return;
    }

    recoveryCount++;
    lastRecoveryTime = now;

    if (!opts.autoReload) {
      log(`Error 3000 detected (#${recoveryCount}) — autoReload disabled, not reloading.`);
      return;
    }

    log(`Error 3000 detected, reloading (#${recoveryCount})...`);
    saveAndReload();
  }

  function onDomMutation() {
    // 防抖：連續 DOM 變動時只檢查一次
    if (debounceTimer) return;
    debounceTimer = setTimeout(() => {
      debounceTimer = null;
      triggerCheck();
    }, DEBOUNCE_MS);
  }

  function startObserver() {
    const target = document.body || document.documentElement;
    if (!target) return;
    const observer = new MutationObserver(onDomMutation);
    observer.observe(target, { childList: true, subtree: true });
  }

  // 兜底：定期做一次全量掃描（極端情況下 DOM 沒變但錯誤仍然存在）
  function startFallbackPoll() {
    setInterval(() => {
      if (!debounceTimer) triggerCheck();
    }, FALLBACK_POLL_MS);
  }

  // SPA 換片：重置節流狀態並重新記錄起點
  function onLocationChange() {
    const now = normalizeUrl(location.href);
    if (now === lastSavedUrl) return;
    log('Route changed, resetting recovery state');
    lastSavedUrl = now;
    lastSavedTime = null;
    recoveryCount = 0;
    lastRecoveryTime = 0;
    lastFullscreenState = false;
    saveHeartbeat();
  }

  // ---- 初始化 ----

  function init() {
    tryRestore();

    setInterval(() => {
      onLocationChange();
      saveHeartbeat();
    }, HEARTBEAT_MS);

    setInterval(() => {
      recoveryCount = 0;
    }, RESET_INTERVAL_MS);

    document.addEventListener('fullscreenchange', onFullscreenChange);

    // 等頁面渲染穩定後啟動 observer
    setTimeout(() => {
      startObserver();
      startFallbackPoll();
    }, OBSERVER_DELAY_MS);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    setTimeout(init, 0);
  }

  return { triggerCheck, isError3000Visible, getVodTime };
}

  createTwitchRecovery(createStorageAdapter());
})();
